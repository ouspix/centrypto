"""Broaden detection without selecting future winners; preserve old execution rules."""
import collections,hashlib,json
import numpy as np
from common import *

def detect(symbol,a,btc,replay,period,cohort):
    b,valid=replay.five(a);ret=b[:,3]/b[:,0]-1;threshold,scale=(.02,3) if cohort=='strict' else (.01,2)
    events=[];cool=-1
    for j in np.flatnonzero(valid & (ret>=threshold)):
        at=replay.START+(j+1)*5*MIN
        if at<ms(period['signal_start']) or at>=replay.END-91*MIN or j<288:continue
        hvalid=valid[j-288:j]
        if hvalid.sum()<144:continue
        std=float(np.std(ret[j-288:j][hvalid],ddof=1));med=float(np.median(b[j-288:j][hvalid,4]));rv=b[j,4]/med if med>0 else 0
        if ret[j]<scale*std or rv<scale or not valid[j-6:j].all() or b[j,3]<=b[j-6:j,1].max():continue
        if not np.isfinite(btc[j]).all() or ret[j]<=btc[j,3]/btc[j,0]-1 or at<cool:continue
        cool=at+120*MIN
        events.append({'symbol':symbol,'alert_idx':int(j*5+4),'alert_time':iso(at),'five_minute_return_pct':float(ret[j]*100),'relative_volume':float(rv),'baseline_complete_bars':int(hvalid.sum()),'alert_low':float(b[j,2]),'period':period['id'],'cohorts':[cohort]})
    return events

def main():
    replay=module('original_replay',OLD/'replay.py');events=[];trades=[];quality=[];rejects=collections.Counter()
    for period in SPEC['periods']:
        arrays,q=period_arrays(period);quality+=q;replay.START=ms(period['start']);replay.END=ms(period['end']);replay.N=(replay.END-replay.START)//MIN
        btc,_=replay.five(arrays['BTC']);pe=[]
        for symbol,a in arrays.items():
            union={}
            for cohort in ['strict','broader']:
                for e in detect(symbol,a,btc,replay,period,cohort):
                    if e['alert_time'] in union:union[e['alert_time']]['cohorts'].append(cohort)
                    else:union[e['alert_time']]=e
            episode_start=None
            for e in sorted(union.values(),key=lambda e:e['alert_time']):
                at=ms(e['alert_time'])
                if episode_start is None or at-episode_start>=120*MIN:episode_start=at
                e['group']=symbol+'|'+iso(episode_start);e['group_time']=iso(episode_start);pe.append(e)
                for mode in ['continuation','immediate']:
                    signal,err=replay.setup(a,e,mode)
                    if err:rejects[mode+':'+err]+=1;continue
                    for slip in [0,5,10]:
                        t,err=replay.execute(a,e,mode,signal,slip)
                        if err:rejects[mode+':'+str(slip)+':'+err]+=1;continue
                        if t['return_pct'] is None:rejects['unresolved_outcome']+=1;continue
                        t['key']='|'.join([symbol,mode,t['entry_time']]);t['cohorts']='|'.join(e['cohorts']);trades.append(t)
        events+=pe;print(period['id'],'alerts',len(pe),'strategy rows',sum(t['period']==period['id'] and t['slippage_bps_per_side']==0 for t in trades),flush=True)
    # Do not double-count an identical strategy entry generated by nearby alert variants.
    unique={}
    for t in sorted(trades,key=lambda t:(t['alert_time'],t['key'],t['slippage_bps_per_side'])):
        k=(t['key'],t['slippage_bps_per_side'])
        if k not in unique:unique[k]=t
        else:rejects['duplicate_strategy_entry']+=1
    trades=list(unique.values());old=csvrows(OLD/'trades.csv');now={(t['key'],float(t['slippage_bps_per_side'])):t for t in trades};matched=0;mismatched=[];missing=[]
    for t in old:
        k=('|'.join([t['symbol'],t['mode'],t['entry_time']]),float(t['slippage_bps_per_side']))
        if k not in now:missing.append(k);continue
        if abs(float(t['return_pct'])-now[k]['return_pct'])>1e-9:mismatched.append(k)
        else:matched+=1
    assert not mismatched, mismatched[:3]
    original_keys={'|'.join([t['symbol'],t['mode'],t['entry_time']]) for t in old}
    for t in trades:t['original_entry']=t['key'] in original_keys
    zer=[t for t in trades if t['slippage_bps_per_side']==0]
    save('events.json',events);writecsv('trades.csv',trades);writecsv('candle-quality.csv',quality)
    save('cohort-summary.json',{'alerts':len(events),'alert_symbols':len(set(e['symbol'] for e in events)),'unique_signal_episodes':len(set(e['group'] for e in events)),'candidate_entries':len(zer),'entry_episodes':len(set(t['group'] for t in zer)),'source_candle_rows':sum(q['source_rows'] for q in quality),'invalid_candles':sum(q['invalid_rows'] for q in quality),'entries_by_period':dict(collections.Counter(t['period'] for t in zer)),'entries_by_mode':dict(collections.Counter(t['mode'] for t in zer)),'dates_with_entries':len(set(t['entry_time'][:10] for t in zer)),'original_rows_reconciled':matched,'original_rows_missing':len(missing),'rejections':dict(rejects)})
    save('cohort-lineage.json',{'original_trades_sha256':hashlib.sha256((OLD/'trades.csv').read_bytes()).hexdigest(),'spec_sha256':hashlib.sha256((HERE/'spec.json').read_bytes()).hexdigest(),'execution_source_sha256':hashlib.sha256((OLD/'replay.py').read_bytes()).hexdigest()})
    print((HERE/'cohort-summary.json').read_text(),flush=True)
if __name__=='__main__':main()
